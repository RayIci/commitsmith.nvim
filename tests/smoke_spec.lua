describe("setup", function()
  it("registers :Commitsmith with completion and no keymaps", function()
    local before = #vim.api.nvim_get_keymap("n")
    require("commitsmith").setup({})
    ok(vim.fn.exists(":Commitsmith") == 2, ":Commitsmith exists")
    eq({ "generate" }, vim.fn.getcompletion("Commitsmith gen", "cmdline"))
    eq(before, #vim.api.nvim_get_keymap("n"), "setup() maps no keys")
  end)

  it("rejects an unknown subcommand", function()
    require("commitsmith").setup({})
    local seen = require("helpers").notifications(function()
      vim.cmd("Commitsmith nope")
    end)
    eq(vim.log.levels.ERROR, seen[1].level)
    ok(seen[1].msg:find("Unknown subcommand `nope`", 1, true), seen[1].msg)
  end)
end)
